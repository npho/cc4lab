"""Copy jaxborg's locked package versions into cc4lab's uv constraints.

A dependency (git or path) contributes only its loose specifiers to cc4lab's
resolve, not its lockfile, so a fresh `uv lock` here drifts from the versions
jaxborg's parity suite was run against (observed: jaxmarl main, flax,
mujoco-mjx). This script reads the jaxborg `git` URL and `rev` from
`[tool.uv.sources]` in pyproject.toml, shallow-fetches exactly that commit into
a temp directory, exports its uv.lock, and rewrites the generated blocks of
`[tool.uv] override-dependencies` / `constraint-dependencies`. Git-sourced
packages (cyborg, jaxmarl) are emitted as override URLs, since constraints
cannot carry URLs.

Needs network access to the jaxborg remote. Run after changing `rev`, then
`uv lock`:

    uv run python scripts/pin_jaxborg_lock.py && uv lock
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = ROOT / "pyproject.toml"
BEGIN, END = "# BEGIN jaxborg-lock (generated by scripts/pin_jaxborg_lock.py)", "# END jaxborg-lock"


def jaxborg_source() -> tuple[str, str]:
    """(git url, full 40-char rev) from ``[tool.uv.sources].jaxborg``."""
    src = tomllib.loads(PYPROJECT.read_text())["tool"]["uv"]["sources"]["jaxborg"]
    url, rev = src.get("git"), src.get("rev")
    if not url or not rev or not re.fullmatch(r"[0-9a-f]{40}", rev):
        raise SystemExit(f"[tool.uv.sources].jaxborg needs `git` and a full 40-char `rev`, got {src}")
    return url, rev


def export_lock(url: str, rev: str) -> list[str]:
    with tempfile.TemporaryDirectory(prefix="jaxborg-") as tmp:
        for cmd in (
            ["git", "init", "-q"],
            ["git", "fetch", "-q", "--depth", "1", url, rev],
            ["git", "checkout", "-q", "FETCH_HEAD"],
        ):
            subprocess.run(cmd, cwd=tmp, check=True)
        out = subprocess.check_output(
            [
                "uv", "export", "--frozen", "--all-extras", "--no-hashes", "--no-emit-project",
                "--no-dev", "--no-header", "--no-annotate",
            ],
            cwd=tmp,
            text=True,
        )
    return [ln.strip() for ln in out.splitlines() if ln.strip() and not ln.startswith(("#", "-e"))]


def render(lines: list[str], indent: str = "    ") -> str:
    body = "\n".join(f'{indent}"{ln.replace(chr(34), chr(39))}",' for ln in lines)
    return f"{indent}{BEGIN}\n{body}\n{indent}{END}"


def main() -> int:
    url, rev = jaxborg_source()
    lines = export_lock(url, rev)
    urls = [ln for ln in lines if " @ " in ln]
    pins = [ln for ln in lines if " @ " not in ln]
    text = PYPROJECT.read_text()
    pattern = re.compile(rf"^[ \t]*{re.escape(BEGIN)}.*?{re.escape(END)}", re.S | re.M)
    blocks = pattern.findall(text)
    if len(blocks) != 2:
        print(f"expected 2 generated blocks (overrides, constraints) in {PYPROJECT}, found {len(blocks)}")
        return 1
    replacements = iter([render(urls), render(pins)])
    text = pattern.sub(lambda _: next(replacements), text)
    PYPROJECT.write_text(text)
    print(f"wrote {len(urls)} override URLs and {len(pins)} version constraints from jaxborg {rev[:7]} uv.lock")
    return 0


if __name__ == "__main__":
    sys.exit(main())
